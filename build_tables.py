"""Render every number used in the paper from the study outputs into results/paper_tables.md."""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

RES = Path(sys.argv[1] if len(sys.argv) > 1 else "results")
DEVICES = ["cpu", "gpu", "npu", "mobile_cpu", "dsp"]
MODELS = ["Ridge", "RidgeLog", "Lasso", "GaussianProcess", "RandomForest", "GradientBoosting"]
FEATURES = ["M0_size_only", "M1n_no_thermal_state", "M1_size_memory", "M2_size_memory_sparse",
            "M3_full_descriptors"]
UNITS = {"duration_s": "s", "energy_j": "J", "temp_rise_c": "°C"}
DIGITS = {"duration_s": 2, "energy_j": 2, "temp_rise_c": 3}


def pct(x, d=1):
    return f"{100 * x:.{d}f}%"


def num(x, d=2):
    return f"{x:.{d}f}"


def table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def load_json(name):
    return json.loads((RES / name).read_text())


out = ["# Paper tables (generated by build_tables.py — do not edit by hand)", ""]
meta = load_json("metadata.json")
out += ["## T1 Configuration", "",
        f"- Status: {meta['status']}",
        f"- Seed {meta['seed']}; {len(meta['families'])} families × {meta['per_family']} workloads = "
        f"{meta['total_workloads']} workloads; {len(meta['devices'])} devices; {len(meta['contexts'])} contexts; "
        f"{meta['repeats']} repeats; {meta['total_rows']:,} rows",
        f"- Training workloads per fold: {meta['training_workloads_per_fold']} "
        f"({meta['training_workloads_per_training_family']} per training family); split sizes (rows): "
        f"{meta['split_sizes_rows']}",
        f"- Feature dimensions: {meta['feature_configs']}",
        f"- Conformal target {meta['coverage_target']}; Mondrian min calibration rows "
        f"{meta['mondrian_min_calibration_rows']}; GP training subset {meta['gp_max_training_rows']} rows",
        f"- Skipped fits: {len(meta['skipped_fits'])}; fits with convergence warnings by model: "
        f"{meta['fits_with_convergence_warnings_by_model']}",
        f"- Runtime: {meta['runtime_s']} s", ""]

rc = pd.read_csv(RES / "regime_device_counts.csv")
rc_t = pd.DataFrame({
    "Device": rc.device, "τ (s)": rc.tau_s.map(lambda v: num(v, 1)),
    "Max t (s)": rc.max_duration_s.map(lambda v: num(v, 1)),
    "Max t/τ": rc.max_duration_over_tau.map(num),
    "Transient rows": rc.transient, "Transition rows": rc.transition, "Saturation rows": rc.saturation})
tot = rc[["transient", "transition", "saturation"]].sum()
out += ["## T2 Regime membership by device", "", table(rc_t), "",
        f"Totals: transient {tot.transient:,} ({pct(tot.transient / tot.sum())}), transition "
        f"{tot.transition:,} ({pct(tot.transition / tot.sum())}), saturation {tot.saturation:,} "
        f"({pct(tot.saturation / tot.sum())})", ""]

rs = pd.read_csv(RES / "regime_rank_support.csv")
out += ["## T3 Device-ranking support", "",
        f"Families with every device present in both transient and saturation regimes: "
        f"{int(rs.ranking_comparable.sum())}/{len(rs)}",
        f"Devices present in the saturation regime (union over families): "
        f"{sorted(set(';'.join(rs.saturation_devices.fillna('')).split(';')) - {''})}",
        f"Saturation rows per family: min {rs.saturation_rows.min()}, max {rs.saturation_rows.max()}", ""]

cs = load_json("cooling_summary.json")
cc = pd.read_csv(RES / "cooling_by_context.csv")
cc_t = pd.DataFrame({
    "Context (Ta, T0) °C": [f"({a:.0f}, {s:.0f})" for a, s in zip(cc.ambient_c, cc.start_temp_c)],
    "T0 − Ta (°C)": cc.start_elevation_c.map(lambda v: num(v, 0)),
    "Mean P·R (°C)": cc.mean_steady_state_rise_c.map(num),
    "Net-cooling share": cc.cooling_share.map(pct),
    "Mean ΔT (°C)": cc.mean_temp_change_c.map(num)})
out += ["## T4 Net cooling by context", "", table(cc_t), "",
        f"Overall net-cooling share: {pct(cs['net_cooling_share_measured'])} measured, "
        f"{pct(cs['net_cooling_share_noise_free'])} noise-free; mean ΔT {num(cs['mean_temp_change_cooling_rows_c'])} °C "
        f"(cooling rows) and +{num(cs['mean_temp_change_heating_rows_c'])} °C (heating rows); minimum ΔT "
        f"{num(cs['min_temp_change_c'])} °C ({cs['min_temp_change_device']}); maximum ΔT "
        f"+{num(cs['max_temp_change_c'])} °C", ""]

sr = load_json("sign_rule_check.json")
out += ["## T5 Sign rule P·R < T0 − Ta", "",
        f"Agreement with measured sign: {pct(sr['agreement_with_measured_sign'], 2)}; with noise-free sign: "
        f"{pct(sr['agreement_with_noise_free_sign'], 2)}; mismatched rows: {sr['mismatch_rows']:,}; share of "
        f"mismatches whose noise-free |ΔT| < 3σ ({3 * sr['sensor_noise_sd_c']:.2f} °C): "
        f"{pct(sr['mismatch_share_with_abs_true_change_below_3_sigma'], 2)}", ""]

al = load_json("energy_thermal_alignment.json")
fm, pk, ss = al["final_temp_measured"], al["peak_temp_ideal"], al["steady_state_rise"]
out += ["## T6 Energy-optimal device versus thermal criteria", "",
        f"Task instances: {al['task_instances']:,}", "",
        table(pd.DataFrame({
            "Thermal criterion": ["End-of-run temperature (measured)", "Peak temperature (noise-free, ties allowed)",
                                  "Steady-state rise P·R"],
            "Energy-optimal device is coolest": [pct(fm["energy_opt_is_coolest_share"]),
                                                 pct(pk["energy_opt_in_coolest_set_share"]),
                                                 pct(ss["energy_opt_is_lowest_share"])],
            "Energy-optimal device is hottest": [f"{pct(fm['energy_opt_is_hottest_share'])} ({fm['energy_opt_is_hottest_count']})",
                                                 pct(pk["energy_opt_unique_hottest_share"]),
                                                 pct(ss["energy_opt_is_highest_share"])]})), "",
        f"Instances where all five peaks tie at T0 (every device cools): {pct(pk['all_devices_tied_at_start_temp_share'])}", ""]
ac = pd.read_csv(RES / "energy_thermal_alignment_by_context.csv")
out += [table(pd.DataFrame({
    "Context (Ta, T0) °C": [f"({a:.0f}, {s:.0f})" for a, s in zip(ac.ambient_c, ac.start_temp_c)],
    "Energy-opt = lowest end temp": ac.energy_opt_is_lowest_final_share.map(pct),
    "Energy-opt in coolest-peak set": ac.energy_opt_in_coolest_peak_share.map(pct),
    "All peaks tied": ac.all_peaks_tied_share.map(pct)})), ""]

cf = pd.read_csv(RES / "device_choice_frequencies.csv")
out += ["## T7 Device selection frequencies", "", table(pd.DataFrame({
    "Device": cf.device, "Lowest energy": cf.lowest_energy_share.map(pct),
    "Lowest end temp": cf.lowest_final_temp_share.map(pct),
    "Highest end temp": cf.highest_final_temp_share.map(pct),
    "Lowest P·R": cf.lowest_steady_state_rise_share.map(pct),
    "Highest P·R": cf.highest_steady_state_rise_share.map(pct)})), ""]

dt = pd.read_csv(RES / "device_thermal_summary.csv")
out += ["## T8 Device thermal summary", "", table(pd.DataFrame({
    "Device": dt.device, "Mean t (s)": dt.mean_duration_s.map(num), "Mean P (W)": dt.mean_power_w.map(num),
    "Mean E (J)": dt.mean_energy_j.map(num), "Mean P·R (°C)": dt.mean_steady_state_rise_c.map(num),
    "Mean ΔT (°C)": dt.mean_temp_change_c.map(num), "Net-cooling share": dt.cooling_share.map(pct),
    "Mean cooling rate (°C/s)": dt.mean_cooling_rate_c_per_s.map(lambda v: num(v, 3))})), ""]

ps = pd.read_csv(RES / "prediction_summary.csv")
fam_all = ps[(ps.protocol == "family_holdout") & (ps.method == "global") & (ps.stratum_type == "all")]
out += ["## T9 Family-holdout accuracy (MAE; 90% split-conformal coverage; mean interval width)", ""]
for target in UNITS:
    rows = []
    for model in MODELS:
        row = {"Model": model}
        for feat in FEATURES:
            r = fam_all[(fam_all.target == target) & (fam_all.model == model) & (fam_all.feature_config == feat)]
            d = DIGITS[target]
            row[feat] = "—" if r.empty else (f"{num(r.mae.iloc[0], d)} / {pct(r.coverage.iloc[0])} / "
                                             f"{num(r.mean_width.iloc[0], d)}")
        rows.append(row)
    out += [f"### {target} ({UNITS[target]})", "", table(pd.DataFrame(rows)), ""]
spread = fam_all[fam_all.feature_config == "M3_full_descriptors"]
out += ["Fold-level coverage range (global method, M3):", "", table(pd.DataFrame({
    "Target": spread.target, "Model": spread.model,
    "Min fold coverage": spread.fold_coverage_min.map(pct), "Max fold coverage": spread.fold_coverage_max.map(pct)})), ""]

pc = pd.read_csv(RES / "protocol_comparison.csv")
out += ["## T10 Random-workload split versus family holdout (same split sizes)", "", table(pd.DataFrame({
    "Target": pc.target, "Model": pc.model, "Features": pc.feature_config,
    "Family-holdout MAE": [num(v, DIGITS[t]) for v, t in zip(pc.family_holdout_mae, pc.target)],
    "Random-split MAE": [num(v, DIGITS[t]) for v, t in zip(pc.random_split_mae, pc.target)],
    "Ratio (family/random)": (pc.family_holdout_mae / pc.random_split_mae).map(num),
    "95% CI of random − family": [f"[{num(a, DIGITS[t])}, {num(b, DIGITS[t])}]"
                                  for a, b, t in zip(pc.ci_low, pc.ci_high, pc.target)]})), ""]
rnd_all = ps[(ps.protocol == "random_workload") & (ps.method == "global") & (ps.stratum_type == "all")]
out += ["Coverage under random split (global method):", "", table(pd.DataFrame({
    "Target": rnd_all.target, "Model": rnd_all.model, "Features": rnd_all.feature_config,
    "Coverage": rnd_all.coverage.map(pct)})), ""]

out += ["## T11 Coverage by true regime under family holdout", ""]
reg = ps[(ps.protocol == "family_holdout") & (ps.stratum_type.isin(["all", "true_regime"]))]
for target, feat in [("duration_s", "M3_full_descriptors"), ("energy_j", "M3_full_descriptors"),
                     ("temp_rise_c", "M3_full_descriptors"), ("duration_s", "M2_size_memory_sparse")]:
    rows = []
    for model in MODELS:
        sub = reg[(reg.target == target) & (reg.model == model) & (reg.feature_config == feat)]
        for method in ["global", "device_mondrian", "predicted_regime_mondrian", "normalized"]:
            m = sub[sub.method == method].set_index("stratum")
            if m.empty:
                continue
            row = {"Model": model, "Method": method}
            for s in ["all", "transient", "transition", "saturation"]:
                row[s] = f"{pct(m.coverage[s])} ({num(m.mean_width[s], DIGITS[target])})" if s in m.index else "—"
            row["MAE saturation"] = num(m.mae["saturation"], DIGITS[target]) if "saturation" in m.index else "—"
            row["Fallback rows"] = pct(m.fallback_share["all"])
            rows.append(row)
    n = reg[(reg.target == target) & (reg.method == "global") & (reg.model == "Ridge")
            & (reg.feature_config == feat)].set_index("stratum").n
    out += [f"### {target}, {feat} — coverage (mean width); rows: "
            + ", ".join(f"{k} {int(v):,}" for k, v in n.items()), "", table(pd.DataFrame(rows)), ""]

dev = ps[(ps.protocol == "family_holdout") & (ps.stratum_type == "device") & (ps.feature_config == "M3_full_descriptors")
         & (ps.model == "GradientBoosting")]
out += ["## T12 Coverage by device (GradientBoosting, M3, family holdout)", ""]
for target in UNITS:
    sub = dev[dev.target == target]
    piv = sub.pivot(index="method", columns="stratum", values="coverage").reindex(columns=DEVICES)
    out += [f"### {target}", "", table(piv.map(pct).reset_index()), ""]

bc = pd.read_csv(RES / "bootstrap_comparisons.csv")
out += ["## T13 Paired workload bootstrap (family holdout; gain = MAE(baseline) − MAE(comparison))", "",
        table(pd.DataFrame({
            "Target": bc.target, "Baseline": bc.baseline, "Comparison": bc.comparison,
            "Baseline MAE": [num(v, DIGITS[t]) for v, t in zip(bc.baseline_mae, bc.target)],
            "Comparison MAE": [num(v, DIGITS[t]) for v, t in zip(bc.comparison_mae, bc.target)],
            "Gain": [num(v, DIGITS[t]) for v, t in zip(bc.mean_gain, bc.target)],
            "Relative": (bc.mean_gain / bc.baseline_mae).map(pct),
            "95% CI": [f"[{num(a, DIGITS[t])}, {num(b, DIGITS[t])}]" for a, b, t in zip(bc.ci_low, bc.ci_high, bc.target)],
            "Workloads": bc.workloads})), ""]

ff = pd.read_csv(RES / "family_fold_metrics.csv")
out += ["## T14 Per-family MAE (GradientBoosting, M3, family holdout)", ""]
g = ff[(ff.model == "GradientBoosting") & (ff.feature_config == "M3_full_descriptors")]
piv = g.pivot(index="test_group", columns="target", values="mae")[list(UNITS)]
cov = g.pivot(index="test_group", columns="target", values="coverage")[list(UNITS)]
fam_t = pd.DataFrame({"Held-out family": piv.index})
for t in UNITS:
    fam_t[f"{t} MAE"] = piv[t].map(lambda v, t=t: num(v, DIGITS[t])).to_numpy()
    fam_t[f"{t} coverage"] = cov[t].map(pct).to_numpy()
out += [table(fam_t.sort_values("Held-out family")), ""]

cw = pd.read_csv(RES / "convergence_warnings.csv")
if len(cw):
    out += ["## T15 Fits with convergence warnings", "",
            table(cw.groupby(["protocol", "model", "feature_config"]).size().rename("fits").reset_index()), ""]

(RES / "paper_tables.md").write_text("\n".join(out), encoding="utf-8")
print(f"wrote {RES / 'paper_tables.md'}")
